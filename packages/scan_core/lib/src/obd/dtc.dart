const _systems = ['P', 'C', 'B', 'U'];

/// Код неисправности из двух байт: старшие 2 бита — система (P/C/B/U),
/// следующие 2 — первая цифра, остальные 12 бит — три hex-цифры.
String decodeDtc(int a, int b) {
  final digits = ((a & 0x0F) << 8 | b).toRadixString(16).padLeft(3, '0');
  return '${_systems[a >> 6]}${(a >> 4) & 0x03}${digits.toUpperCase()}';
}

/// Обратное к [decodeDtc]: 'P0171' → [0x01, 0x71].
List<int> encodeDtc(String code) {
  final system = _systems.indexOf(code[0].toUpperCase());
  if (system < 0 || code.length != 5) {
    throw FormatException('Неверный код неисправности', code);
  }
  final d1 = int.parse(code[1]);
  final rest = int.parse(code.substring(2), radix: 16);
  return [system << 6 | d1 << 4 | rest >> 8, rest & 0xFF];
}

/// Коды из ответа режимов 03 (сохранённые), 07 (ожидающие), 0A (постоянные).
/// На CAN после байта режима идёт число кодов, на старых протоколах — сразу пары
/// байт, добитые нулями до шести. Повторы от разных блоков убираются.
List<String> parseDtcResponse(
  List<List<int>> messages, {
  required int mode,
  required bool isCan,
}) {
  final codes = <String>{};
  for (final m in messages) {
    if (m.isEmpty || m[0] != 0x40 + mode) continue;
    var data = m.sublist(1);
    if (isCan) {
      if (data.isEmpty) continue;
      final count = data[0];
      data = data.sublist(1);
      if (data.length > count * 2) data = data.sublist(0, count * 2);
    }
    for (var i = 0; i + 1 < data.length; i += 2) {
      if (data[i] == 0 && data[i + 1] == 0) continue;
      codes.add(decodeDtc(data[i], data[i + 1]));
    }
  }
  return codes.toList();
}

/// Описание по устройству кода, если конкретного нет в [commonDtcDescriptions].
String describeDtcKind(String code) {
  final system = switch (code[0]) {
    'P' => 'двигатель и трансмиссия',
    'C' => 'шасси',
    'B' => 'кузов',
    'U' => 'сеть блоков',
    _ => 'неизвестная система',
  };
  // SAE J2012: у P общие 0, 2 и P34xx–P3Fxx; у C, B, U — 0 и 3.
  final generic = switch (code[1]) {
    '0' => true,
    '2' => code[0] == 'P',
    '3' => code[0] != 'P' || code.compareTo('P34') >= 0,
    _ => false,
  };
  return '$system, ${generic ? 'общий код SAE' : 'код производителя'}';
}

String describeDtc(String code) =>
    commonDtcDescriptions[code] ?? describeDtcKind(code);

