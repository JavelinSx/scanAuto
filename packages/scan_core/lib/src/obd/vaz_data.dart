/// Данные производителя ВАЗ: блок Итэлма M74 CAN (Лада Гранта), запрос `22 00 01`
/// по адресу двигателя 7E0, ответ — 63 байта, начиная с `62 00 01`.
///
/// Раскладка восстановлена по записи 19.11.2026 (Гранта 11186, калибровка
/// I445GBT2): каждый байт сопоставлен со стандартными PID той же поездки,
/// совпадение 0.98–0.997, и сходится со старой раскладкой с форума клуба Гранты
/// (напряжение ÷ 10, температура ×0.75 − 48, обороты ÷ 4). Остальные байты пока
/// не известны — сырой ответ пишется в запись целиком для дальнейшего разбора.
library;

/// Ряд, который пишется в запись и уходит в пакет для ИИ, но не PID режима 01.
final class ExtraSeries {
  const ExtraSeries(this.key, this.name, this.unit, {this.decimals = 1});

  final String key;
  final String name;
  final String unit;
  final int decimals;
}

/// Чего нет в стандартном OBD Гранты: PID 42 (напряжение блока) она не отдаёт,
/// а ATRV адаптера на клоне завышает почти на вольт (15.2 В против 14.4 В у блока).
const vazSeries = [
  ExtraSeries('ecu_voltage', 'Напряжение бортсети (по блоку)', 'В'),
];

abstract final class VazBlock0001 {
  static const command = '220001';
  static const length = 63;

  /// Расшифрованные значения или null, если это не полный ответ на 22 00 01.
  /// Кроме [vazSeries] — то же, что и в стандартных PID (для сверки раскладки).
  static Map<String, double>? decode(List<int> m) {
    if (m.length < length || m[0] != 0x62 || m[1] != 0x00 || m[2] != 0x01) {
      return null;
    }
    return {
      'ecu_voltage': m[4] / 10,
      'coolant': m[6] * 0.75 - 48,
      'rpm': (m[7] << 8 | m[8]) / 4,
      'ltft1': m[30] * 100 / 128 - 100,
      'iat': m[36] * 0.75 - 48,
    };
  }
}
